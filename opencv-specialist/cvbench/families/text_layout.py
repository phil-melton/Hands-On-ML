# Calibrated by calibrate() on 4000 gauge blocks of the scene population (6 upright Hershey faces, scale
# 0.5-2.5, thickness 1-3, strings reaching the cap height; OpenCV 5.0.0.93), values are the constant that
# would *just* be needed, with TOL_C0 = SIZE_C0 = 1 px:
#   centring of the reference idiom (centre the getTextSize box, baseline included)
#       tau_x 0.052, tau_y 0.143   (ink low by (h - cap)/2: always one-sided, 0.03 .. 0.17 of ih)
#       the ink-centred idiom: 0.5 px at most; the textbook idiom without the baseline: tau_y 0.228
#   reported size minus ink extent, as a fraction of ih:
#       width  in [-0.059, +0.196]   (bearings; a leading "j" hooks out of the box)
#       height in [-0.118, +0.300]   (line height vs descenders / no descenders)
# Margin ~25 % on each: TOL_X 0.065, TOL_Y 0.18, SIZE_W (0.075, 0.25), SIZE_H (0.15, 0.375).
# What the population restriction buys (same measurement on the excluded blocks):
#       strings that do not reach the cap height (n=200): tau_y 0.346 (vs 0.143)
#       the two script faces (n=200):                     tau_x 0.078, width slack lo 0.123 (vs 0.059)
# Layer 2, scenes (n=400, 5.0.0): ink box minus the scratch render of putText at the reported scale: 0 px
# in both axes, so DIM_TOL = 1 px is one quantum (a fringe pixel whose coverage x contrast is below half a
# grey level on the real canvas but not on the scratch one). Strongest ink pixel: coverage 0.985 .. 1.0 on
# the scenes, but down to 0.867 on the gauge blocks (a 1-px stroke at scale 0.5 never gets full coverage:
# 5.0 anti-aliases every Hershey glyph); spread between channels <= 0.0015. ALPHA_MIN = 0.8 keeps ~50 % of
# the worst deficit (0.133) as margin; ALPHA_SPREAD = 0.01 is one grey level over the minimum contrast of 100.
# Shrink: the reference lands at 0.971 .. 1.009 x s_fit (3 % steps); the contract floor is 0.9.
# META_POS: the reference moves the ink by exactly SHIFT in 300 scenes (0 px error); 1 px is the origin
# quantum (banker's rounding of a float origin breaks exact covariance: "int_rounding" errs by 1 px in
# ~1/3 of the scenes). "longer string": the reference uses at most 40 % of the allowed centre movement.
# META_DIM: ink size under the shift: identical in 300 scenes (integers, so no tolerance).
TOL_X, TOL_Y, TOL_C0 = 0.065, 0.18, 1.0
SIZE_W = (0.075, 0.25)  # tw - iw  in [-(SIZE_W[0]*ih + SIZE_C0), SIZE_W[1]*ih + SIZE_C0]
SIZE_H = (0.15, 0.375)  # th - ih  likewise
SIZE_C0 = 1.0
DIM_TOL = 1
ALPHA_MIN, ALPHA_SPREAD = 0.8, 0.01
META_POS, META_DIM = 1.0, 0


@dataclass(eq=False)
class Scene:
    img: np.ndarray
    box: tuple[int, int, int, int]  # x, y, w, h
    text: str
    face: int
    scale: float  # requested font scale
    thickness: int
    color: tuple[int, int, int]
    shrink: bool  # True when the text does not fit at `scale` and has to be reduced
    s_fit: float  # largest scale <= `scale` at which the getTextSize box (+ baseline) fits the box
    seed: int


@dataclass
class Verdict:
    ok: bool
    reason: str = ""

    def __bool__(self) -> bool:
        return self.ok


# ---------------------------------------------------------------- measurement helpers

def _ink_box(text: str, face: int, scale: float, thickness: int, line_type: int = cv2.LINE_8) -> tuple[int, int, int, int]:
    """Ink bounding box (x0, y0, x1, y1), inclusive, relative to the putText origin, from a scratch render."""
    (tw, th), base = cv2.getTextSize(text, face, scale, thickness)
    pad = 30 + int(30 * scale)
    canvas = np.zeros((th + base + 2 * pad, tw + 2 * pad, 3), np.uint8)
    org = (pad, pad + th)
    cv2.putText(canvas, text, org, face, scale, (255, 255, 255), thickness, line_type)
    ys, xs = np.nonzero(canvas.any(axis=2))
    return int(xs.min()) - org[0], int(ys.min()) - org[1], int(xs.max()) - org[0], int(ys.max()) - org[1]


def _ink_dims(text: str, face: int, scale: float, thickness: int) -> tuple[int, int]:
    x0, y0, x1, y1 = _ink_box(text, face, scale, thickness)
    return x1 - x0 + 1, y1 - y0 + 1


def _reaches_cap(text: str, face: int, scale: float, thickness: int) -> bool:
    """Population test: the ink rises to (at least 90 % of) the cap height of the same face, scale and thickness."""
    top = -_ink_box(text, face, scale, thickness)[1]
    cap = -_ink_box("H", face, scale, thickness)[1]
    return top >= 0.9 * cap


def _fits(text: str, face: int, scale: float, thickness: int, w: int, h: int) -> bool:
    (tw, th), base = cv2.getTextSize(text, face, scale, thickness)
    return tw <= w and th + base <= h


def _placed_ink_inside(text: str, face: int, scale: float, thickness: int, w: int, h: int) -> bool:
    """Does the reference placement (centre the getTextSize box) keep all of its ink inside a w x h box?"""
    (tw, th), base = cv2.getTextSize(text, face, scale, thickness)
    ox, oy = (w - tw) // 2, (h - th - base) // 2 + th
    x0, y0, x1, y1 = _ink_box(text, face, scale, thickness)
    return ox + x0 >= 0 and oy + y0 >= 0 and ox + x1 < w and oy + y1 < h


def _ink_mask(img: np.ndarray, canvas: np.ndarray | None = None) -> np.ndarray:
    """Ink = pixels that differ from the input canvas (verify_manufactured) or from the corner pixel (metamorphic)."""
    ref = img[0, 0] if canvas is None else canvas
    return np.any(img != ref, axis=2)


def _bbox(mask: np.ndarray) -> tuple[int, int, int, int] | None:
    rows, cols = np.flatnonzero(mask.any(axis=1)), np.flatnonzero(mask.any(axis=0))
    if rows.size == 0:
        return None
    return int(cols[0]), int(rows[0]), int(cols[-1]), int(rows[-1])


def _centre(bb: tuple[int, int, int, int]) -> tuple[float, float]:
    """Centre of an inclusive pixel bounding box, in continuous coordinates (pixel edges at integers)."""
    return (bb[0] + bb[2] + 1) / 2, (bb[1] + bb[3] + 1) / 2


def _peak_alpha(img: np.ndarray, canvas: np.ndarray, color: tuple[int, int, int]) -> np.ndarray:
    """Per-channel coverage (p - bg) / (colour - bg) of the strongest ink pixel."""
    d = np.abs(img.astype(np.int16) - canvas.astype(np.int16)).sum(axis=2)
    py, px = np.unravel_index(int(np.argmax(d)), d.shape)
    b = canvas[py, px].astype(float)
    return (img[py, px].astype(float) - b) / (np.asarray(color, float) - b)


# ---------------------------------------------------------------- scene generation

WORDS = ("Total Price Frame Count Status Temp Speed Scan Result Level Name Value Zone Width Height Angle Gain Offset "
         "Quick brown fox jumps over lazy dog Alpha Beta Gamma Delta Sensor Camera Lens Pixel Edge Corner Blob "
         "gypsy jump query pigpen ounce cause user mean").split()
SYMBOLS = ".,:-+%=/()#"


def _rand_text(rng: np.random.Generator) -> str:
    toks = []
    for _ in range(int(rng.integers(1, 4))):
        kind = int(rng.integers(0, 10))
        if kind < 6:
            w = WORDS[int(rng.integers(len(WORDS)))]
            toks.append(w.lower() if rng.random() < 0.3 else w)
        elif kind < 8:
            toks.append(str(int(rng.integers(0, 10000))))
        elif kind < 9:
            toks.append(f"{rng.uniform(0, 100):.{int(rng.integers(0, 3))}f}")
        else:
            toks.append(WORDS[int(rng.integers(len(WORDS)))].upper()[:4] + SYMBOLS[int(rng.integers(len(SYMBOLS)))]
                        + str(int(rng.integers(0, 99))))
    return " ".join(toks)[:22].strip()


def make_scene(seed: int) -> Scene:
    """Manufacture a scene from its answer. Even seeds: the text fits at the requested scale. Odd seeds: it must shrink."""
    rng = np.random.default_rng(seed)
    shrink = bool(seed % 2)
    for _ in range(4000):
        face = FACES[int(rng.integers(len(FACES)))]
        thickness = int(rng.integers(1, 4))
        s_star = round(float(rng.uniform(0.5, 2.0)), 2)  # the answer: the scale the text is finally drawn at
        text = _rand_text(rng)
        if len(text) < 3 or not _reaches_cap(text, face, s_star, thickness):
            continue
        (tw, th), base = cv2.getTextSize(text, face, s_star, thickness)
        if tw > 520:
            continue
        if not shrink:
            bw = tw + 2 * int(rng.integers(3, int(0.25 * tw) + 4))
            bh = th + base + 2 * int(rng.integers(3, int(0.8 * th) + 4))
            s_req = s_fit = s_star
            drawn = (s_star,)
        else:
            # which dimension limits the scale: both (the box is the text's own aspect), the width, or the height
            limit = ("both", "width", "height")[int(rng.integers(3))]
            bw, bh = tw + int(rng.integers(0, 4)), th + base + int(rng.integers(0, 4))
            if limit == "width":
                bh = int(round((th + base) * float(rng.uniform(1.15, 2.0))))
            elif limit == "height":
                bw = int(round(tw * float(rng.uniform(1.15, 2.0))))
            s_req = round(s_star * float(rng.uniform(1.2, 2.2)), 2)
            iw, ih = _ink_dims(text, face, s_req, thickness)
            if iw < 1.1 * bw and ih < 1.1 * bh:  # the ink must clearly overflow at the requested scale
                continue
            s_fit = s_req
            while not _fits(text, face, s_fit, thickness, bw, bh):
                s_fit = round(s_fit - 0.01, 2)
            drawn = (s_fit, round(0.97 * s_fit, 4))  # scales the reference lands on
        if not all(_placed_ink_inside(text, face, s, thickness, bw, bh) for s in drawn):
            continue  # the answer must be realisable: its ink has to fit the box
        H = bh + int(rng.integers(2 * MARGIN + 12, 2 * MARGIN + 120))
        W = bw + int(rng.integers(2 * MARGIN + 12, 2 * MARGIN + 200))
        x = int(rng.integers(MARGIN, W - bw - MARGIN + 1))
        y = int(rng.integers(MARGIN, H - bh - MARGIN + 1))
        bg = rng.integers(0, 256, size=3)
        color = tuple(int(rng.integers(b + 100, 256)) if b < 128 else int(rng.integers(0, b - 99)) for b in bg)
        img = np.empty((H, W, 3), np.uint8)
        img[:] = bg.astype(np.uint8)
        return Scene(img, (x, y, bw, bh), text, face, float(s_req), thickness, color, shrink, float(s_fit), seed)
    raise RuntimeError(f"no scene found for seed {seed}")


def inputs(scene: Scene) -> dict:
    return {"img": scene.img, "box": [int(v) for v in scene.box], "text": scene.text, "face": int(scene.face),
            "scale": float(scene.scale), "thickness": int(scene.thickness), "color": [int(c) for c in scene.color]}


# ---------------------------------------------------------------- verifiers

def verify_manufactured(scene: Scene, out: dict) -> Verdict:
    problems = check_outputs(SPEC, out)
    if problems:
        return Verdict(False, "contract: " + "; ".join(problems))
    img = np.asarray(out["img"])
    if img.shape != scene.img.shape:
        return Verdict(False, f"image shape {img.shape}, expected {scene.img.shape}")
    ts = np.asarray(out["text_size"]).ravel()
    if ts.size != 2:
        return Verdict(False, f"text_size has {ts.size} values, expected (width, height)")
    x, y, w, h = scene.box

    # layer 1.1: containment
    ink = _ink_mask(img, scene.img)
    bb = _bbox(ink)
    if bb is None:
        return Verdict(False, "nothing was drawn")
    outside = ink.copy()
    outside[y:y + h, x:x + w] = False
    if outside.any():
        return Verdict(False, f"{int(outside.sum())} changed pixels outside the box {scene.box}; ink bbox "
                              f"x {bb[0]}..{bb[2]}, y {bb[1]}..{bb[3]}")
    iw, ih = bb[2] - bb[0] + 1, bb[3] - bb[1] + 1

    # layer 2.4: scale rule
    r = float(out["scale"])
    if not r > 0:
        return Verdict(False, f"scale {r} is not positive")
    if not scene.shrink:
        if abs(r - scene.scale) > 1e-9:
            return Verdict(False, f"the text fits at scale {scene.scale}, but scale {r:.4g} was used")
    elif not (SHRINK_FLOOR * scene.s_fit - 1e-9 <= r < scene.scale):
        return Verdict(False, f"scale {r:.4g} outside [{SHRINK_FLOOR * scene.s_fit:.4g}, {scene.scale}): the largest "
                              f"scale that fits is {scene.s_fit}")

    # layer 2.5: glyph size
    ref_w, ref_h = _ink_dims(scene.text, scene.face, r, scene.thickness)
    if abs(iw - ref_w) > DIM_TOL or abs(ih - ref_h) > DIM_TOL:
        return Verdict(False, f"ink is {iw}x{ih} px, but putText draws {ref_w}x{ref_h} at scale {r:.4g} with the "
                              f"requested face and thickness")

    # layer 1.2: centring
    cx, cy = _centre(bb)
    ex, ey = cx - (x + w / 2), cy - (y + h / 2)
    tol_x, tol_y = TOL_X * ih + TOL_C0, TOL_Y * ih + TOL_C0
    if abs(ex) > tol_x or abs(ey) > tol_y:
        return Verdict(False, f"ink centre is off the box centre by ({ex:+.1f}, {ey:+.1f}) px, allowed "
                              f"(±{tol_x:.1f}, ±{tol_y:.1f})")

    # layer 1.3: reported size against the ink
    tw, th = (int(v) for v in ts)
    dw, dh = tw - iw, th - ih
    if not -(SIZE_W[0] * ih + SIZE_C0) <= dw <= SIZE_W[1] * ih + SIZE_C0:
        return Verdict(False, f"reported width {tw} vs ink width {iw}: difference {dw:+d} px outside "
                              f"[{-(SIZE_W[0] * ih + SIZE_C0):.1f}, {SIZE_W[1] * ih + SIZE_C0:.1f}]")
    if not -(SIZE_H[0] * ih + SIZE_C0) <= dh <= SIZE_H[1] * ih + SIZE_C0:
        return Verdict(False, f"reported height {th} vs ink height {ih}: difference {dh:+d} px outside "
                              f"[{-(SIZE_H[0] * ih + SIZE_C0):.1f}, {SIZE_H[1] * ih + SIZE_C0:.1f}]")

    # layer 2.6: colour
    alpha = _peak_alpha(img, scene.img, scene.color)
    if alpha.min() < ALPHA_MIN or alpha.max() > 1 + ALPHA_SPREAD or alpha.max() - alpha.min() > ALPHA_SPREAD:
        return Verdict(False, f"the strongest ink pixel is not the requested colour {list(scene.color)}: per-channel "
                              f"coverage {np.round(alpha, 2).tolist()}")
    return Verdict(True)


def transforms(scene: Scene) -> dict[str, dict]:
    """Symmetries of the task: shift the box (the ink follows), append characters (the centre stays)."""
    x, y, w, h = scene.box
    return {
        NAME_SHIFT: inputs(replace(scene, box=(x + SHIFT[0], y + SHIFT[1], w, h))),
        NAME_LONGER: inputs(replace(scene, text=scene.text + EXTRA)),
    }


def _out_ink(name: str, out: dict) -> tuple[tuple[int, int, int, int] | None, str]:
    problems = check_outputs(SPEC, out)
    if problems:
        return None, f"{name}: contract: " + "; ".join(problems)
    return _bbox(_ink_mask(np.asarray(out["img"]))), ""


def verify_metamorphic(base: dict, variants: dict[str, dict]) -> Verdict:
    bb0, err = _out_ink("original", base)
    if err:
        return Verdict(False, err)
    for name, out in variants.items():
        bb, err = _out_ink(name, out)
        if err:
            return Verdict(False, err)
        if (bb is None) != (bb0 is None):
            return Verdict(False, f"{name}: ink {'vanished' if bb is None else 'appeared'} against the original output")
        s0, s1 = float(base["scale"]), float(out["scale"])
        if name == NAME_SHIFT:
            if not np.array_equal(np.asarray(base["text_size"]), np.asarray(out["text_size"])) or abs(s0 - s1) > 1e-9:
                return Verdict(False, f"{name}: scale/text_size changed ({s0:.4g} -> {s1:.4g}) although only the box moved")
            if bb is None:
                continue  # nothing drawn in either: vacuously invariant (the stuck-gauge blind spot)
            moved = (bb[0] - bb0[0], bb[1] - bb0[1])
            if abs(moved[0] - SHIFT[0]) > META_POS or abs(moved[1] - SHIFT[1]) > META_POS:
                return Verdict(False, f"{name}: ink moved by {moved}, expected {SHIFT} (±{META_POS:g})")
            d0, d1 = (bb0[2] - bb0[0], bb0[3] - bb0[1]), (bb[2] - bb[0], bb[3] - bb[1])
            if abs(d0[0] - d1[0]) > META_DIM or abs(d0[1] - d1[1]) > META_DIM:
                return Verdict(False, f"{name}: ink size changed from {d0[0] + 1}x{d0[1] + 1} to {d1[0] + 1}x{d1[1] + 1} px")
        elif name == NAME_LONGER:
            if s1 > s0 + 1e-9:
                return Verdict(False, f"{name}: a longer string got a larger scale ({s0:.4g} -> {s1:.4g})")
            if bb is None:
                continue
            ih0, ih1 = bb0[3] - bb0[1] + 1, bb[3] - bb[1] + 1
            c0, c1 = _centre(bb0), _centre(bb)
            lim_x, lim_y = TOL_X * (ih0 + ih1) + 2 * TOL_C0, TOL_Y * (ih0 + ih1) + 2 * TOL_C0
            if abs(c1[0] - c0[0]) > lim_x or abs(c1[1] - c0[1]) > lim_y:
                return Verdict(False, f"{name}: ink centre moved by ({c1[0] - c0[0]:+.1f}, {c1[1] - c0[1]:+.1f}) px, "
                                      f"allowed (±{lim_x:.1f}, ±{lim_y:.1f})")
            if abs(s1 - s0) <= 1e-9 and (bb[2] - bb[0] < bb0[2] - bb0[0] - META_DIM
                                         or bb[3] - bb[1] < bb0[3] - bb0[1] - META_DIM):
                return Verdict(False, f"{name}: at an unchanged scale the longer string has a smaller ink box")
        else:
            return Verdict(False, f"unknown variant {name!r}")
    return Verdict(True)


