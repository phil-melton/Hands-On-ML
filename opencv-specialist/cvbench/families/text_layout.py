def _gauge(text: str, face: int, scale: float, thickness: int) -> dict:
    """One gauge block: a single string. Ink box vs the getTextSize box, and the centring error of three idioms."""
    x0, y0, x1, y1 = _ink_box(text, face, scale, thickness)
    (tw, th), base = cv2.getTextSize(text, face, scale, thickness)
    iw, ih = x1 - x0 + 1, y1 - y0 + 1
    pad = 30 + int(30 * scale)
    canvas = np.zeros((th + base + 2 * pad, tw + 2 * pad), np.uint8)
    cv2.putText(canvas, text, (pad, pad + th), face, scale, 255, thickness)
    peak = int(canvas.max()) / 255  # strongest coverage of any ink pixel (white on black)
    bw, bh = tw + 10, th + base + 10  # any box that holds the text; offsets are position-independent
    orgs = {
        "baseline_ignored": ((bw - tw) // 2, (bh - th) // 2 + th),  # the textbook idiom
        "metric_box": ((bw - tw) // 2, (bh - th - base) // 2 + th),  # the reference: centre (tw, th + baseline)
        "ink_centred": ((bw - iw) // 2 - x0, (bh - ih) // 2 - y0),  # measure the ink, centre that
    }
    err = {k: (ox + (x0 + x1 + 1) / 2 - bw / 2, oy + (y0 + y1 + 1) / 2 - bh / 2) for k, (ox, oy) in orgs.items()}
    overhang = max(0, -x0, x1 - (tw - 1), -(y0 + th), y1 - (base - 1))  # ink outside the getTextSize box, px
    return {"ih": ih, "iw": iw, "dw": tw - iw, "dh": th - ih, "err": err, "overhang": overhang, "peak": peak}


def _need(vals: list[float], ihs: list[float], c0: float) -> float:
    """Smallest tau such that |v| <= tau * ih + c0 for every gauge block."""
    return max((abs(v) - c0) / i for v, i in zip(vals, ihs))


def _draw(inp: dict) -> dict:
    """In-process twin of the reference, used by calibrate() on scenes."""
    img, (x, y, w, h), text, face, s, thick, color = (inp[k] for k in ("img", "box", "text", "face", "scale",
                                                                      "thickness", "color"))
    (tw, th), base = cv2.getTextSize(text, face, s, thick)
    while (tw > w or th + base > h) and s > 0.1:
        s = round(s * 0.97, 4)
        (tw, th), base = cv2.getTextSize(text, face, s, thick)
    out = img.copy()
    cv2.putText(out, text, (x + (w - tw) // 2, y + (h - th - base) // 2 + th), face, s, tuple(color), thick)
    return {"img": out, "text_size": np.array([tw, th]), "scale": float(s)}


def calibrate(n: int = 4000, seed: int = 12345, n_scenes: int = 400, scene_seed: int = 70_000,
              n_side: int | None = None) -> dict:
    """Measure, on single-string gauge blocks (faces x scales x thicknesses x strings), the quantities the
    tolerances are about. Centring and size slack are reported as the constant that would *just* be needed
    (tau at TOL_C0 / SIZE_C0); the constants carry a margin over these. ``n_side`` blocks each of the two
    excluded populations (strings below the cap height, script faces) are measured for comparison."""
    rng = np.random.default_rng(seed)
    n_side = max(50, n // 20) if n_side is None else n_side
    quota = {"tall": n, "short": n_side, "script": n_side}
    pops: dict[str, list] = {k: [] for k in quota}
    lt_diff = 0
    while any(len(pops[k]) < quota[k] for k in quota):
        scale = round(float(rng.uniform(0.5, 2.5)), 2)
        thickness = int(rng.integers(1, 4))
        text = _rand_text(rng)
        if len(text) < 1:
            continue
        script = rng.random() < 0.1
        face = (SCRIPT_FACES if script else FACES)[int(rng.integers(2 if script else len(FACES)))]
        tall = _reaches_cap(text, face, scale, thickness)
        pop = "script" if script else ("tall" if tall else "short")
        if len(pops[pop]) < quota[pop] and (pop != "script" or tall):
            pops[pop].append(_gauge(text, face, scale, thickness))
            if len(pops[pop]) <= 100:  # does lineType change any pixel?
                (tw, th), base = cv2.getTextSize(text, face, scale, thickness)
                imgs = []
                for lt in (cv2.LINE_4, cv2.LINE_8, cv2.LINE_AA):
                    im = np.zeros((th + base + 20, tw + 20), np.uint8)
                    cv2.putText(im, text, (10, 10 + th), face, scale, 255, thickness, lt)
                    imgs.append(im)
                lt_diff += int(not (np.array_equal(imgs[0], imgs[1]) and np.array_equal(imgs[1], imgs[2])))
    out: dict = {"n_blocks": {k: len(v) for k, v in pops.items()}, "lineType_changes_pixels_of_300": lt_diff}
    for pop, blocks in pops.items():
        if not blocks:
            continue
        ihs = [b["ih"] for b in blocks]
        out[pop] = {
            "centre": {idiom: {"tau_x": round(_need([b["err"][idiom][0] for b in blocks], ihs, TOL_C0), 3),
                               "tau_y": round(_need([b["err"][idiom][1] for b in blocks], ihs, TOL_C0), 3),
                               "max_abs_px": round(max(abs(v) for b in blocks for v in b["err"][idiom]), 2)}
                       for idiom in ("metric_box", "baseline_ignored", "ink_centred")},
            "size_w": {"lo": round(max((-b["dw"] - SIZE_C0) / b["ih"] for b in blocks), 3),
                       "hi": round(max((b["dw"] - SIZE_C0) / b["ih"] for b in blocks), 3)},
            "size_h": {"lo": round(max((-b["dh"] - SIZE_C0) / b["ih"] for b in blocks), 3),
                       "hi": round(max((b["dh"] - SIZE_C0) / b["ih"] for b in blocks), 3)},
            "overhang_px_max": max(b["overhang"] for b in blocks),
            "peak_coverage_min": round(min(b["peak"] for b in blocks), 4),
        }
    # scene level: the reference against the layer-2 reference render and the colour model
    dim_diff, ratio, alpha_min, alpha_spread, alpha_max, fails = 0, [], 9.0, 0.0, 0.0, 0
    for i in range(n_scenes):
        sc = make_scene(scene_seed + i)
        res = _draw(inputs(sc))
        fails += int(not verify_manufactured(sc, res))
        x0, y0, x1, y1 = _bbox(_ink_mask(res["img"], sc.img))
        rw, rh = _ink_dims(sc.text, sc.face, res["scale"], sc.thickness)
        dim_diff = max(dim_diff, abs(x1 - x0 + 1 - rw), abs(y1 - y0 + 1 - rh))
        a = _peak_alpha(res["img"], sc.img, sc.color)
        alpha_min, alpha_max, alpha_spread = min(alpha_min, a.min()), max(alpha_max, a.max()), max(alpha_spread, a.max() - a.min())
        if sc.shrink:
            ratio.append(res["scale"] / sc.s_fit)
    out["scenes"] = {"n": n_scenes, "reference_fails_verifier": fails, "dim_diff_vs_render_max": dim_diff,
                     "peak_alpha_min": round(float(alpha_min), 4), "peak_alpha_max": round(float(alpha_max), 4),
                     "peak_alpha_spread_max": round(float(alpha_spread), 4),
                     "shrink_scale_over_s_fit": (round(min(ratio), 4), round(max(ratio), 4))}
    return out


def measure_metamorphic_drift(n: int = 300, seed: int = 50_000) -> dict:
    """How far the reference strays from the symmetries: position error of the shift, size changes, centre moves."""
    worst = {"shift_pos": 0.0, "shift_dim": 0.0, "longer_centre_ratio": 0.0, "scale_increase": 0.0, "narrowed": 0}
    for i in range(n):
        sc = make_scene(seed + i)
        base = _draw(inputs(sc))
        bb0 = _bbox(_ink_mask(base["img"]))
        for name, inp in transforms(sc).items():
            out = _draw(inp)
            bb = _bbox(_ink_mask(out["img"]))
            if name == NAME_SHIFT:
                worst["shift_pos"] = max(worst["shift_pos"], abs(bb[0] - bb0[0] - SHIFT[0]), abs(bb[1] - bb0[1] - SHIFT[1]))
                worst["shift_dim"] = max(worst["shift_dim"], abs((bb[2] - bb[0]) - (bb0[2] - bb0[0])),
                                         abs((bb[3] - bb[1]) - (bb0[3] - bb0[1])))
            else:
                ih0, ih1 = bb0[3] - bb0[1] + 1, bb[3] - bb[1] + 1
                c0, c1 = _centre(bb0), _centre(bb)
                lim_x, lim_y = TOL_X * (ih0 + ih1) + 2 * TOL_C0, TOL_Y * (ih0 + ih1) + 2 * TOL_C0
                worst["longer_centre_ratio"] = max(worst["longer_centre_ratio"], abs(c1[0] - c0[0]) / lim_x,
                                                   abs(c1[1] - c0[1]) / lim_y)
                worst["scale_increase"] = max(worst["scale_increase"], out["scale"] - base["scale"])
                if out["scale"] == base["scale"] and (bb[2] - bb[0] < bb0[2] - bb0[0] or bb[3] - bb[1] < bb0[3] - bb0[1]):
                    worst["narrowed"] += 1
    return worst


