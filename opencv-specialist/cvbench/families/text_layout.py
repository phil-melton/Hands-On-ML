def reference_solve(img, box, text, face, scale, thickness, color):
    x, y, w, h = box
    s = scale
    (tw, th), base = cv2.getTextSize(text, face, s, thickness)
    while (tw > w or th + base > h) and s > 0.1:
        s = round(s * 0.97, 4)
        (tw, th), base = cv2.getTextSize(text, face, s, thickness)
    org = (x + (w - tw) // 2, y + (h - th - base) // 2 + th)
    out = img.copy()
    cv2.putText(out, text, org, face, s, tuple(color), thickness)
    return {"img": out, "text_size": np.array([tw, th]), "scale": float(s)}


