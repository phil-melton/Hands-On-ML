"""Family ``text_layout``: centre a string in a box; verified by containment, not by pixels.

Manufactured solution
---------------------
Choose the answer first: a string, a Hershey face, a stroke thickness and the font scale s* the
string is drawn at. The scene is built from it. The target box is the ``getTextSize`` box at s*
(width, height + baseline) plus a margin, so the text fits at the scale it is asked for
(``shrink=False``); or the same box with 0-3 px of slack, in one or both dimensions (the other one
is then 15-100 % roomier), while the *requested* scale is 1.2-2.2x larger, so the text has to be
shrunk (``shrink=True``) and the width, the height or both decide by how much. The manufactured
answer is then a placement
(the text centred in the box), a scale (the requested one, or s_fit, the largest scale at which the
getTextSize box still fits) and the box size that ``getTextSize`` reports at that scale.

Tolerance law
-------------
Between OpenCV versions the metrics and the glyph bitmaps move: ``getTextSize("OpenCV 5", SIMPLEX,
1, 2)`` was (155, 22) with baseline 10 on 4.14 and is (136, 27) with baseline 6 on 5.0, and 13 % of
the pixels of a rendered string differ (probes/results/diff_4.14_vs_5.0.md). So no pixel is ever
compared with a stored picture. What stays true when a font changes is *geometry*:

Layer 1: font-agnostic, true for any font in any version. ``ink`` = pixels that differ from the input
canvas; ``ih`` = height of the ink bounding box; lengths in px.
  1. Containment: no pixel outside the box changes, and something is drawn.
  2. Centring: the centre of the ink bounding box is within  TOL * ih + TOL_C0  of the centre of the
     box, per axis. The error has two parts, both known from the physics of the metrics. (a) The metric
     box and the ink disagree. On 5.0 the line height is 27 px at scale 1 while the cap height is 21 px
     (4.14 reported 22 for the probe string), so centring the getTextSize box leaves the ink (h - cap)/2 *low*: a systematic,
     one-sided shift proportional to the font size. Left and right bearings are nearly symmetric, so the
     horizontal disagreement is much smaller: separate TOL_X and TOL_Y. (b) Integer origins: floor
     division moves the origin by up to 1/2 px and the ink edges are quantised to 1/2 px, whatever the
     scale: TOL_C0 = 1 px.
  3. Reported size: the (width, height) the solution reports for the getTextSize box must lie within a
     calibrated slack of the ink extent: the box contains the ink up to bearings and ascender headroom
     (proportional to ih); it can be taller than the ink (no descender) or shorter (descenders hang
     below the line height).

Layer 2: contract compliance, regenerated by the installed OpenCV at verification time, so it is
immune to a font change as well (another version redraws its own reference):
  4. Scale: the reported ``scale`` equals the requested one when the text fits, and otherwise lies in
     [SHRINK_FLOOR * s_fit, requested). SHRINK_FLOOR is part of the task statement, not a measurement:
     "up to 10 % below the largest scale that fits is accepted".
  5. Glyph size: the ink bounding box (width, height) equals that of ``putText`` at the reported scale,
     face and thickness on a scratch canvas, within DIM_TOL px. Without it, tiny text (or the wrong
     face) is centred and contained, so it would pass layer 1.
  6. Colour: the strongest ink pixel lies on the segment background -> requested colour at coverage
     >= ALPHA_MIN. (Not an exact match: see "5.0 findings".)

Population. Layer 1.2 is sharp only where the metric box and the ink agree about what "the line" is.
Scenes therefore contain upright Hershey faces (not the two script faces, whose slant puts ink outside
the getTextSize box and would double the reported-width slack) and strings whose ink reaches the cap
height (a capital, a digit or an ascender); a string like "ounce" has an x-height ink box and the
contract is ambiguous there (the price is recorded next to the constants). Ambiguity at the fit
decision is excluded the same way: in no-shrink scenes the getTextSize box fits with a >= 3 px margin,
in shrink scenes the *ink* overflows by >= 10 % at the requested scale, so solutions that decide
"fits" by the metric box or by the ink agree. Finally a scene is only accepted if the reference
placement keeps its own ink inside the box: glyphs can overhang the getTextSize box (a leading "j" hooks
2-4 px to the left of the origin), and a box with 0-3 px of slack could otherwise reject a correct answer.

5.0 findings made on the way (OpenCV 5.0.0.93, measured, see calibrate())
  * cv2.putText ignores ``lineType`` for Hershey fonts: LINE_4, LINE_8 and LINE_AA give bit-identical,
    anti-aliased images (about 200 grey levels per string). 4.x drew LINE_8 text with two levels; this is
    the +55 % non-zero pixels of the probe ``putText_hershey_pixels``. Hence the coverage-based colour check.
  * getTextSize's height is now the font's line height, independent of the string (27 px at scale 1 for
    SIMPLEX), and its baseline is the string's own descent (0 for "HHH", 6 for "OpenCV 5"; 4.14 gave
    height 22 and baseline 10 for "OpenCV 5"). The cap height is 21 px, so 6 px of headroom sit above it.

Metamorphic checks (``verify_metamorphic`` receives outputs only, no scene or box)
----------------------------------------------------------------------------------
The canvas background is uniform, so the ink is every pixel that differs from the corner pixel.
  * ``shift``: moving the box by SHIFT moves the ink bounding box by SHIFT (covariant, +-META_POS px for
    rounding) and keeps its size, the reported scale and the reported size (invariant).
  * ``longer string``: appending characters in the same box leaves the centre of the ink where it was (both
    centres are within their own band of the same box centre, so they differ by at most the sum of the
    bands), never increases the reported scale, and at an unchanged scale never narrows or shortens the
    ink (the old glyphs are still there).
Their blind spot is the usual one: an output that is constant (nothing drawn at all) is invariant under
every symmetry, so they complement the manufactured gate and do not replace it.
"""
